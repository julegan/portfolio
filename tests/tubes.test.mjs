import assert from "node:assert/strict";
import {DEFAULTS,WEIGHTS,PALETTES,sanitizeSettings,dimensions,makeGrid,newProject,normalizeProject,patternMarkdown,maxFloat} from "../dist/projects/tubes/engine.mjs";
const s=sanitizeSettings(DEFAULTS);
const d=dimensions(s);
assert.equal(d.stitches,120);
assert.equal(d.rounds,84);
assert.equal(d.actualCircumference,24);
assert.equal(d.actualHeight,12);
const a=makeGrid(s),b=makeGrid(s);
assert.deepEqual(a.grid,b.grid,"Seeded generation must be reproducible");
assert.equal(a.grid.length,84);
assert(a.grid.every(row=>row.length===120),"Each round must have cast-on stitches");
assert(a.grid.flat().every(cell=>cell.color>=0&&cell.color<s.colors&&["k","p"].includes(cell.stitch)));
assert.equal(dimensions({...s,repeats:11}).stitches,132,"Repeat count must alter circumference");
assert.equal(dimensions({...s,repeats:11}).actualCircumference,26.4);
const scene={...s,arrangement:"scene",design:"landscape",vertical:"once",circumference:27};
assert.equal(dimensions(scene).stitches,136,"Scene stitches derive from target size and gauge");
const texture={...s,colors:1,texture:true};
const t=makeGrid(texture);
assert(t.grid.some(row=>row.some(cell=>cell.stitch==="p")),"Optional purl stitches must render");
assert(t.grid.flat().every(cell=>cell.color===0));
const project=newProject();
project.overrides=[{r:0,c:0,color:3,stitch:"p"}];
const reopened=normalizeProject(JSON.parse(JSON.stringify(project)));
assert.equal(makeGrid(reopened.settings,reopened.overrides).grid[0][0].stitch,"p");
assert.equal(makeGrid(reopened.settings,reopened.overrides).grid[0][0].color,3);
assert.throws(()=>normalizeProject({...project,version:2}),/supported/);
assert.throws(()=>normalizeProject({...project,overrides:[{r:-1,c:0,color:0,stitch:"k"}]}),/invalid/);
assert.throws(()=>dimensions({...s,motifWidth:30,repeats:12}),/limit/);
const md=patternMarkdown(reopened,makeGrid(reopened.settings,reopened.overrides));
assert(md.includes("Round 1:"));
assert(md.includes("Cast on: 120 stitches"));
assert(md.includes("C4:"));
assert.equal(typeof maxFloat(a.grid,s.colors),"number");
assert.equal(WEIGHTS.worsted.st,20);
assert.equal(PALETTES.electric.length,6);
console.log("Tubes engine tests passed.");